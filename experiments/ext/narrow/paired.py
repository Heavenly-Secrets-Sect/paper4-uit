"""Merge ext_narrow runs with the a2b_pselect rows of the same seeds, check the pairing, and apply the
pre-registered rule of docs/ext/narrow.md mechanically.

Run: python experiments/ext/narrow/paired.py   (writes results/ext_narrow_eval/ruling.md)
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
RES = ROOT / "results"


def load(name, methods=None):
    rows = []
    p = RES / name / "runs.jsonl"
    if not p.exists():
        return rows
    for line in open(p):
        r = json.loads(line)
        if methods is None or r["method"] in methods:
            rows.append(r)
    return rows


def key(r):
    return (r["topology"], r["replicate"], r["T"], r["kind"], r["rate"])


def index(rows):
    return {(key(r), r["method"]): r for r in rows if r["status"] == "ok" and r.get("iscore_nonnull_mean") is not None}


def cell_stats(rows, m, T, kind, rate):
    g = [r for r in rows if r["method"] == m and r["T"] == T and r["kind"] == kind and r["rate"] == rate]
    ok = [r for r in g if r["status"] == "ok"]
    if not ok:
        return None
    cov = sum(r["n_covered_nonnull"] for r in ok) / sum(r["n_nonnull"] for r in ok)
    return {"n": len(ok), "of": len(g), "cov": cov, "IS": float(np.mean([r["iscore_nonnull_mean"] for r in ok])),
            "width": float(np.median([r["width_kept"] for r in ok if r.get("width_kept") is not None])),
            "n_open": _mean_key(ok, "info_n_open"), "n_open_boot": _mean_key(ok, "info_n_open_boot_mean")}


def _mean_key(rows, k):
    v = [r[k] for r in rows if r.get(k) is not None]
    return float(np.mean(v)) if v else None


def paired(idx, m, ref, T, kind, rate, n_resample=1000):
    diffs = defaultdict(list)
    for (k, meth), r in idx.items():
        if meth == m and k[2] == T and k[3] == kind and k[4] == rate:
            o = idx.get((k, ref))
            if o:
                diffs[k[0]].append(r["iscore_nonnull_mean"] - o["iscore_nonnull_mean"])
    if not diffs:
        return None
    rng = np.random.default_rng(0)
    topos = list(diffs)
    est = float(np.mean([v for t in topos for v in diffs[t]]))
    boots = [np.mean([v for i in rng.choice(len(topos), len(topos)) for v in diffs[topos[i]]]) for _ in range(n_resample)]
    lo, hi = np.quantile(boots, (0.025, 0.975))
    return est, float(lo), float(hi), sum(len(v) for v in diffs.values())


def main():
    ev = load("ext_narrow_eval")
    ab = load("ext_narrow_ablation")
    old = load("a2b_pselect")
    # pairing check: tolerant_v4 rows must be identical
    iv, io = index([r for r in ev if r["method"] == "tolerant_v4"]), index([r for r in old if r["method"] == "tolerant_v4"])
    common = set(iv) & set(io)
    same = sum(1 for k in common if abs(iv[k]["iscore_nonnull_mean"] - io[k]["iscore_nonnull_mean"]) < 1e-12
               and iv[k]["n_covered_nonnull"] == io[k]["n_covered_nonnull"])
    paired_ok = len(common) == len(iv) == len(io) and same == len(common)
    if ab:
        ia = index([r for r in ab if r["method"] == "tolerant_v4"])
        same_ab = sum(1 for k in set(ia) & set(iv) if abs(ia[k]["iscore_nonnull_mean"] - iv[k]["iscore_nonnull_mean"]) < 1e-12)
    rows = ev + [r for r in old if r["method"] in ("plugin", "pselect_union")] + \
        [r for r in ab if r["method"] in ("tolerant_v5_sel", "tolerant_v5_cal2")]
    idx = index(rows)
    Ts = [40, 80, 150]
    cells = [("none", 0.0)] + [(k, r) for k in ("extra", "missing", "reversed") for r in (0.2, 0.5)]
    methods = ["plugin", "lp_allpast", "pselect_union", "tolerant_v4", "tolerant_v5", "tolerant_v5_sel", "tolerant_v5_cal2"]
    out = ["# ext_narrow: ruling (generated by experiments/ext/narrow/paired.py)", "",
           f"Pairing check: tolerant_v4 rows of ext_narrow_eval vs a2b_pselect: {same}/{len(common)} identical "
           f"({len(iv)} vs {len(io)} rows) -> paired with a2b_pselect: **{paired_ok}**"]
    if ab:
        out.append(f"Ablation run tolerant_v4 rows identical to ext_narrow_eval: {same_ab}/{len(ia)}")
    out += ["", "## Cells: coverage / IS / width (n_open, n_open_boot for v5 variants)", "",
            "| T | cell | " + " | ".join(methods) + " |", "|---|---|" + "---|" * len(methods)]
    S = {}
    for T in Ts:
        for kind, rate in cells:
            cs = []
            for m in methods:
                s = cell_stats(rows, m, T, kind, rate)
                S[(m, T, kind, rate)] = s
                if s is None:
                    cs.append("–")
                else:
                    extra = f" ({s['n_open']:.1f}, {s['n_open_boot']:.1f})" if s.get("n_open_boot") else ""
                    cs.append(f"{s['cov']:.3f} / {s['IS']:.2f} / {s['width']:.2f}{extra}" + ("" if s["n"] == s["of"] else f" [{s['n']}/{s['of']}]"))
            out.append(f"| {T} | {kind}-{rate} | " + " | ".join(cs) + " |")
    out += ["", "## Paired IS difference (method - reference), 95% CI clustered by topology", "",
            "| T | cell | v5 - v4 | v5 - pselect_union | v5_sel - v4 | v5_cal2 - v4 | v4 - pselect_union |", "|---|---|---|---|---|---|---|"]
    P = {}
    for T in Ts:
        for kind, rate in cells:
            cs = []
            for m, ref in (("tolerant_v5", "tolerant_v4"), ("tolerant_v5", "pselect_union"), ("tolerant_v5_sel", "tolerant_v4"),
                           ("tolerant_v5_cal2", "tolerant_v4"), ("tolerant_v4", "pselect_union")):
                p = paired(idx, m, ref, T, kind, rate)
                P[(m, ref, T, kind, rate)] = p
                cs.append("–" if p is None else f"{p[0]:+.2f} [{p[1]:+.2f}, {p[2]:+.2f}] (n={p[3]})")
            out.append(f"| {T} | {kind}-{rate} | " + " | ".join(cs) + " |")
    # rule
    out += ["", "## Pre-registered rule", ""]
    verdict = True
    c1 = []
    for rate in (0.2, 0.5):
        s = S[("tolerant_v5", 40, "missing", rate)]; p = P[("tolerant_v5", "tolerant_v4", 40, "missing", rate)]
        ok = s is not None and p is not None and s["cov"] >= 0.90 and p[2] < 0
        c1.append(ok)
        out.append(f"- C1 T=40 missing-{rate}: cov {s['cov']:.3f}, v5-v4 {p[0]:+.2f} [{p[1]:+.2f}, {p[2]:+.2f}] -> {'PASS' if ok else 'FAIL'}")
    c2 = []
    for T in (80, 150):
        for kind in ("extra", "missing", "reversed"):
            for rate in (0.2, 0.5):
                s, v = S[("tolerant_v5", T, kind, rate)], S[("tolerant_v4", T, kind, rate)]
                ok = s["cov"] >= 0.90 and s["IS"] <= 1.05 * v["IS"]
                c2.append(ok)
                out.append(f"- C2 T={T} {kind}-{rate}: cov {s['cov']:.3f}, IS {s['IS']:.3f} vs v4 {v['IS']:.3f} "
                           f"(ratio {s['IS'] / v['IS']:.3f}) -> {'PASS' if ok else 'FAIL'}")
    c3 = []
    for T, kind, rate in [(40, "none", 0.0), (80, "none", 0.0), (150, "none", 0.0)] + \
            [(40, k, r) for k in ("extra", "reversed") for r in (0.2, 0.5)]:
        s, v = S[("tolerant_v5", T, kind, rate)], S[("tolerant_v4", T, kind, rate)]
        ok = s["IS"] <= 1.05 * v["IS"]
        c3.append(ok)
        out.append(f"- C3 T={T} {kind}-{rate}: IS {s['IS']:.3f} vs v4 {v['IS']:.3f} (ratio {s['IS'] / v['IS']:.3f}) -> {'PASS' if ok else 'FAIL'}")
    verdict = all(c1) and all(c2) and all(c3)
    out += ["", f"C1 {sum(c1)}/2, C2 {sum(c2)}/12, C3 {sum(c3)}/{len(c3)} -> **tolerant_v5 {'RETAINED' if verdict else 'REJECTED'}**", ""]
    # A2b-style count vs pselect
    cnt, lines = 0, []
    for T in Ts:
        for kind in ("extra", "missing", "reversed"):
            for rate in (0.2, 0.5):
                s, p = S[("tolerant_v5", T, kind, rate)], P[("tolerant_v5", "pselect_union", T, kind, rate)]
                ok = p is not None and s["cov"] >= 0.90 and p[2] < 0
                cnt += ok
                if not ok:
                    lines.append(f"  - not passed: T={T} {kind}-{rate}: cov {s['cov']:.3f}, diff "
                                 + ("–" if p is None else f"{p[0]:+.2f} [{p[1]:+.2f}, {p[2]:+.2f}]"))
    out += [f"Reported (A2b rule vs pselect_union, paired={paired_ok}): v5 passes {cnt}/18 damaged cells"] + lines
    (RES / "ext_narrow_eval" / "ruling.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
