"""Descriptive tables for the lag_max 1 / 4 runs (no verdict), using analyze.py's helpers, plus the
pairing check of tolerant_v5_1 against results/ext_region51_lag{1,4} on the cells whose runner cell
index is unchanged (T40 none and missing-0.2) and the T40 calibration factors of v5_1.

Run: python experiments/ext/r4levboot/describe_lag.py --lag 1   (and --lag 4)
Writes results/ext_r4levboot_lag<lag>/describe.md and describe.json.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze as A  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lag", type=int, required=True)
    a = ap.parse_args()
    run, ref_run = f"ext_r4levboot_lag{a.lag}", f"ext_region51_lag{a.lag}"
    rows = A.load(run)
    stored = A.load(ref_run)
    keep = lambda r: r["T"] == 40 and (r["kind"], r["rate"]) in (("none", 0.0), ("missing", 0.2))  # noqa: E731
    chk = A.check_identical([r for r in rows if keep(r)], [r for r in stored if keep(r)], A.REF)
    cal = json.loads((A.RES / run / "calibration.json").read_text())
    cal0 = json.loads((A.RES / ref_run / "calibration.json").read_text())
    calchk = {k: (cal.get(f"{A.REF}|40|{k}"), cal0.get(f"{A.REF}|40|{k}")) for k in ("none", "missing", "reversed")}
    cfg = json.loads((A.RES / run / "manifest.json").read_text())["config"]
    cells = [(T, k, r) for T in cfg["T"] for (k, r) in [("none", 0.0)] + [(k, r) for k in cfg["damage"]["kinds"] for r in cfg["damage"]["rates"]]]
    C = A.Cells(rows)
    out = [f"# {run}: descriptive (generated by experiments/ext/r4levboot/describe_lag.py)", "",
           f"Pairing of {A.REF} rows (T40 none + missing-0.2) with results/{ref_run}: {chk['identical']}/{chk['common']} identical -> **{chk['ok']}**", "",
           f"v5_1 T40 runner factors this run vs {ref_run}: {calchk}", ""]
    d, S, methods = A.describe(C, cells, cal)
    out += d
    P = {(m, c): C.paired(m, A.REF, c) for m in methods[1:] for c in cells}
    fam = [(m, c) for m in methods[1:] for c in cells if P[(m, c)]]
    rej = dict(zip(fam, A.holm([P[x]["p2"] for x in fam])))
    out += ["", f"## Paired IS arm − v5_1 (B = {A.B}, seed {A.SEED}); Holm 0.05 over {len(fam)} tests (descriptive)", "",
            "| T | cell | " + " | ".join(methods[1:]) + " |", "|---|---|" + "---|" * (len(methods) - 1)]
    for c in cells:
        out.append(f"| {c[0]} | {c[1]}-{c[2]} | " + " | ".join(
            "–" if P[(m, c)] is None else f"{A.fp(P[(m, c)])} p {P[(m, c)]['p2']:.4f}{' H' if rej.get((m, c)) else ''} (n {P[(m, c)]['n']})"
            for m in methods[1:]) + " |")
    out += ["", f"Holm rejections: {sum(rej.values())}/{len(fam)} (H marks a rejection)."]
    res = {"pairing": chk, "cal_check": calchk, "stats": {f"{m}|{c}": S[(m, c)] for m in methods for c in cells},
           "paired": {f"{m}|{c}": P[(m, c)] for m in methods[1:] for c in cells}, "holm_rejections": sum(rej.values()), "holm_family": len(fam)}
    (A.RES / run / "describe.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    (A.RES / run / "describe.json").write_text(json.dumps(res, indent=1, default=str), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
