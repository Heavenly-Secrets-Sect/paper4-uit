"""Apply the pre-registered rule of r5hubscreen2 (docs/ext/r5hubscreen2.md, section 3) mechanically.

Inputs: results/ext_r5hubscreen2_tests/tests.json (V0), results/ext_r5hubscreen2_p2/runs.jsonl (P2),
results/ext_r5hubscreen2_g/runs.jsonl (no-harm (a)). Output: results/ext_r5hubscreen2_ruling/{ruling.md, ruling.json}.
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
RES = ROOT / "results"
OUT = RES / "ext_r5hubscreen2_ruling"
CAND, V51, V1, PHS = "tolerant_v5_1_hs2", "tolerant_v5_1", "tolerant_v5_1_hs", "plugin_hs_cal"
P2 = [(T, k) for T in (19, 25, 30, 35) for k in ("missing", "reversed", "extra")]
P2C = [(T, k) for T, k in P2 if T <= 25]
G = [(T, k, r) for T in (40, 80, 150) for k, r in [("none", 0.0)] + [(k, r) for k in ("extra", "missing", "reversed") for r in (0.2, 0.5)]]
B = 20_000
ALPHA = 0.05
MIN_CLUSTERS = 8
NI_MARGIN = 1.10
NH_RATIO = 1.03


def load(name):
    p = RES / name / "runs.jsonl"
    return [json.loads(l) for l in open(p)] if p.exists() else []


def rk(r):
    return (r["topology"], r["replicate"], r["T"], r["kind"], r["rate"])


def cell(rows, T, kind, m, rate=None):
    return [r for r in rows if r["T"] == T and r["kind"] == kind and r["method"] == m
            and (rate is None or float(r["rate"]) == rate)]


def stats(g):
    ok = [r for r in g if r["status"] == "ok"]
    nn_all = sum(r["n_nonnull_truth"] for r in g)
    nn_ok = sum(r["n_nonnull"] for r in ok)
    cov = sum(r["n_covered_nonnull"] for r in ok) / nn_ok if nn_ok else float("nan")
    itt = sum(r["n_covered_nonnull"] for r in ok) / nn_all if nn_all else float("nan")
    IS = [r["iscore_nonnull_mean"] for r in ok]
    return {"n": len(g), "ok": len(ok), "cov": cov, "itt": itt, "IS": float(np.mean(IS)) if IS else float("nan"),
            "IS_med": float(np.median(IS)) if IS else float("nan")}


def holm(ps, alpha=ALPHA):
    idx = [i for i, p in enumerate(ps) if p is not None]
    order = sorted(idx, key=lambda i: ps[i])
    m = len(idx)
    rej = [False] * len(ps)
    for rank, i in enumerate(order):
        if ps[i] <= alpha / (m - rank):
            rej[i] = True
        else:
            break
    return rej


def boot_diff_p_worse(d, seed):
    """One-sided cluster-bootstrap p for H0: mean(a - b) <= 0 (topology clusters, run-weighted mean)."""
    topos = list(d)
    sums = np.array([np.sum(d[t]) for t in topos])
    cnts = np.array([len(d[t]) for t in topos])
    rng = np.random.default_rng(seed)
    picks = rng.integers(0, len(topos), size=(B, len(topos)))
    bm = sums[picks].sum(1) / cnts[picks].sum(1)
    return (1 + int((bm <= 0).sum())) / (B + 1)


def boot_ratio(da, db, seed):
    """Cluster bootstrap of mean(a) / mean(b) (pooled over runs); returns (upper 95% one-sided, p for H0 ratio >= margin)."""
    topos = list(da)
    sa = np.array([np.sum(da[t]) for t in topos]); sb = np.array([np.sum(db[t]) for t in topos])
    rng = np.random.default_rng(seed)
    picks = rng.integers(0, len(topos), size=(B, len(topos)))
    ratio = sa[picks].sum(1) / sb[picks].sum(1)
    return float(np.quantile(ratio, 0.95)), (1 + int((ratio >= NI_MARGIN).sum())) / (B + 1)


def paired(rows, T, kind, a, b, rate=None, keys=None):
    ia = {rk(r): r for r in cell(rows, T, kind, a, rate) if r["status"] == "ok"}
    ib = {rk(r): r for r in cell(rows, T, kind, b, rate) if r["status"] == "ok"}
    ks = set(ia) & set(ib)
    if keys is not None:
        ks &= keys
    da, db, dd = defaultdict(list), defaultdict(list), defaultdict(list)
    for k in ks:
        x, y = ia[k]["iscore_nonnull_mean"], ib[k]["iscore_nonnull_mean"]
        da[k[0]].append(x); db[k[0]].append(y); dd[k[0]].append(x - y)
    n = len(ks)
    if not n:
        return {"n": 0, "clusters": 0}
    xa = [v for l in da.values() for v in l]; xb = [v for l in db.values() for v in l]
    return {"n": n, "clusters": len(da), "mean_a": float(np.mean(xa)), "mean_b": float(np.mean(xb)),
            "med_a": float(np.median(xa)), "med_b": float(np.median(xb)),
            "ratio": float(np.mean(xa) / np.mean(xb)), "diff": float(np.mean(xa) - np.mean(xb)),
            "_da": da, "_db": db, "_dd": dd}


def strip(d):
    return {k: v for k, v in d.items() if not k.startswith("_")}


def main():
    global OUT
    ap = argparse.ArgumentParser()
    ap.add_argument("--p2", default="ext_r5hubscreen2_p2")
    ap.add_argument("--g", default="ext_r5hubscreen2_g")
    ap.add_argument("--out", default="ext_r5hubscreen2_ruling")
    a = ap.parse_args()
    OUT = RES / a.out
    OUT.mkdir(parents=True, exist_ok=True)
    p2 = load(a.p2)
    g = load(a.g)
    tests = json.loads((RES / "ext_r5hubscreen2_tests" / "tests.json").read_text())
    J, L = {}, ["# r5hubscreen2: ruling (generated by experiments/ext/r5hubscreen2/analyze.py)", ""]
    # ------------------------------------------------------------------ validity
    v0 = bool(tests["V0"])
    cand_all = [r for r in p2 + g if r["method"] == CAND]
    nonred = [r for r in cand_all if r["hs_reduced"] == 0]
    ident = [r for r in nonred if r["hs_status"] == r["v51_status"] and (r["hs_status"] != "ok" or r["raw_ident_v51"])]
    lag0 = sum(int(r.get("hs_contemp_dropped") or 0) for r in cand_all)
    v1 = len(ident) == len(nonred) and lag0 == 0
    v51ok = [r for r in cand_all if r["v51_status"] == "ok"]
    changed = [r for r in v51ok if not r["raw_ident_v51"]]
    ch_data = sum(1 for r in changed if (r.get("hs_eq_data") or 0) > 0)
    ch_draw = len(changed) - ch_data
    ch_fail = sum(1 for r in changed if r["hs_status"] != "ok")
    J["validity"] = {"V0": v0, "V1": v1, "V1_nonreduced": len(nonred), "V1_identical": len(ident), "lag0_dropped": lag0,
                     "v51_ok_runs": len(v51ok), "v51_ok_changed": len(changed), "changed_data_level": ch_data,
                     "changed_draw_only": ch_draw, "changed_and_hs2_failed": ch_fail}
    L += ["## Validity", "",
          f"- V0 unit tests + D-07H identity probe: {'PASS' if v0 else 'FAIL'}",
          f"- V1 hs2 == v5_1 (status, raw C/lo/hi bit-identical) on every run with hs_reduced = 0 (P2 + G): "
          f"{len(ident)}/{len(nonred)}; lag-0 terms dropped in total: {lag0} -> **{'PASS' if v1 else 'FAIL'}**",
          f"- Honest identity: v5_1-ok runs {len(v51ok)}, changed by hs2 {len(changed)} (reduction at data level {ch_data}, "
          f"in draws only {ch_draw}; hs2 failed on {ch_fail} of them)", ""]
    # ------------------------------------------------------------------ P2
    meths = [CAND, V51, V1, PHS]
    S = {}
    L += ["## P2 cells (lag_max 2, rate 0.2): ok/60 · coverage on completed · ITT · mean IS · median IS", "",
          "| T | cell | reduced | trunc runs | fit/screen fail | " + " | ".join(meths) + " |", "|---|---|---|---|---|" + "---|" * len(meths)]
    for T, k in P2:
        cs = []
        for m in meths:
            s = stats(cell(p2, T, k, m))
            S[(T, k, m)] = s
            cs.append(f"{s['ok']}/{s['n']} · {s['cov']:.3f} · {s['itt']:.3f} · {s['IS']:.2f} · {s['IS_med']:.2f}")
        cg = cell(p2, T, k, CAND)
        nred = sum(r["hs_reduced"] for r in cg)
        ntr = sum(1 for r in cg if (r.get("hs_trunc_eq_total") or 0) > 0)
        ff = sum(int(r.get("hs_fit_fail") or 0) for r in cg); sf = sum(int(r.get("hs_screen_fail") or 0) for r in cg)
        L.append(f"| {T} | {k} | {nred} | {ntr} | {ff}/{sf} | " + " | ".join(cs) + " |")
    p2a_cells = [S[(T, k, CAND)]["ok"] >= 59 and S[(T, k, CAND)]["n"] == 60 for T, k in P2]
    p2a = all(p2a_cells)
    itts = [S[(T, k, CAND)]["itt"] for T, k in P2]
    p2b_n = sum(x >= 0.90 for x in itts)
    p2b = p2b_n >= 10 and min(itts) >= 0.85
    # P2c: rescued runs, ratio of mean IS hs2 / plugin_hs_cal, non-inferiority margin 1.10, Holm over 6
    pc = []
    for i, (T, k) in enumerate(P2C):
        resc = {rk(r) for r in cell(p2, T, k, CAND) if r["v51_status"] != "ok" and r["status"] == "ok"}
        pr = paired(p2, T, k, CAND, PHS, keys=resc)
        pr["rescued"] = len(resc)
        if pr["n"]:
            up, p = boot_ratio(pr["_da"], pr["_db"], 20261106 + i)
            pr["upper95"], pr["p_ni"] = up, p
        else:
            pr["upper95"], pr["p_ni"] = None, None
        pc.append(pr)
    rej = holm([x["p_ni"] for x in pc])
    pc_pass = [rej[i] and pc[i]["clusters"] >= MIN_CLUSTERS for i in range(len(pc))]
    pc_unadj = [x["n"] > 0 and x["upper95"] < NI_MARGIN and x["clusters"] >= MIN_CLUSTERS for x in pc]
    p2c = sum(pc_pass) >= 4
    L += ["", "## P2c: rescued runs (v5_1 not ok, hs2 ok), paired with plugin_hs_cal (both ok)", "",
          "| T | cell | rescued | paired | clusters | mean IS hs2 / plugin_hs_cal | ratio | upper 95% | p (H0 ratio >= 1.10) | Holm(6) | median IS hs2 / plugin_hs_cal | counts |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, (T, k) in enumerate(P2C):
        x = pc[i]
        if x["n"]:
            L.append(f"| {T} | {k} | {x['rescued']} | {x['n']} | {x['clusters']} | {x['mean_a']:.2f} / {x['mean_b']:.2f} | {x['ratio']:.3f} | "
                     f"{x['upper95']:.3f} | {x['p_ni']:.4f} | {'rej' if rej[i] else '-'} | {x['med_a']:.2f} / {x['med_b']:.2f} | "
                     f"{'YES' if pc_pass[i] else 'no'} |")
        else:
            L.append(f"| {T} | {k} | {x['rescued']} | 0 | 0 | – | – | – | – | – | – | no |")
    # descriptive: hs2 vs v5_1 on v5_1-ok runs, hs2 vs v1, rescued coverage
    L += ["", "## Descriptive (not part of the verdict)", "",
          "| T | cell | hs2 vs v5_1 (both ok): n, ratio, diff, p worse, Holm(12) | hs2 vs v1 (both ok): n, ratio | rescued: n, coverage hs2, coverage plugin_hs_cal |",
          "|---|---|---|---|---|"]
    dv = [paired(p2, T, k, CAND, V51) for T, k in P2]
    dv_p = [boot_diff_p_worse(x["_dd"], 20261107 + i) if x["n"] else None for i, x in enumerate(dv)]
    dv_h = holm(dv_p)
    J["descriptive"] = {}
    for i, (T, k) in enumerate(P2):
        x = dv[i]
        y = paired(p2, T, k, CAND, V1)
        resc_rows = [r for r in cell(p2, T, k, CAND) if r["v51_status"] != "ok" and r["status"] == "ok"]
        rkeys = {rk(r) for r in resc_rows}
        ph_rows = [r for r in cell(p2, T, k, PHS) if rk(r) in rkeys]
        sr, sp = stats(resc_rows), stats(ph_rows)
        ok_sig = dv_h[i] and x["clusters"] >= MIN_CLUSTERS
        a = (f"{x['n']}, {x['ratio']:.3f}, {x['diff']:+.3f}, {dv_p[i]:.4f}, {'WORSE' if ok_sig else '-'}" if x["n"] else "n 0")
        b = f"{y['n']}, {y['ratio']:.3f}" if y["n"] else "n 0"
        L.append(f"| {T} | {k} | {a} | {b} | {len(resc_rows)}, {sr['cov']:.3f}, {sp['cov']:.3f} |")
        J["descriptive"][f"{T}|{k}"] = {"vs_v51": strip(x), "vs_v51_p_worse": dv_p[i], "vs_v51_holm_worse": bool(ok_sig),
                                        "vs_v1": strip(y), "rescued": len(resc_rows), "rescued_cov_hs2": sr["cov"],
                                        "rescued_cov_plugin_hs_cal": sp["cov"]}
    # ------------------------------------------------------------------ no-harm (a) on G
    nh, nh_p = [], []
    for i, (T, k, r) in enumerate(G):
        x = paired(g, T, k, CAND, V51, rate=r)
        x["p_worse"] = boot_diff_p_worse(x["_dd"], 20261108 + i) if x["n"] else None
        sc, sv = stats(cell(g, T, k, CAND, r)), stats(cell(g, T, k, V51, r))
        x["cov_hs2"], x["cov_v51"], x["ok_hs2"], x["ok_v51"], x["n_rows"] = sc["cov"], sv["cov"], sc["ok"], sv["ok"], sc["n"]
        x["reduced"] = sum(rr["hs_reduced"] for rr in cell(g, T, k, CAND, r))
        nh.append(x); nh_p.append(x["p_worse"])
    nh_h = holm(nh_p)
    nh_ratio = [x["n"] == 0 or x["ratio"] <= NH_RATIO for x in nh]
    nh_sig = [nh_h[i] and nh[i]["clusters"] >= MIN_CLUSTERS for i in range(len(nh))]
    nh_cov = [not (x["cov_v51"] >= 0.90) or x["cov_hs2"] >= 0.90 for x in nh]
    nh_complete = all(x["n_rows"] == 60 for x in nh)
    nha = all(nh_ratio) and not any(nh_sig) and all(nh_cov) and nh_complete
    L += ["", "## No-harm (a): Gaussian grid G (lag_max 2, 21 cells), hs2 vs v5_1 paired on runs both ok", "",
          "| T | cell | rows | reduced | ok hs2 / v5_1 | paired | ratio | p worse | Holm(21) | coverage hs2 / v5_1 |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for i, (T, k, r) in enumerate(G):
        x = nh[i]
        rat = f"{x['ratio']:.4f}" if x["n"] else "–"
        pw = f"{x['p_worse']:.4f}" if x["n"] else "–"
        L.append(f"| {T} | {k}-{r} | {x['n_rows']} | {x['reduced']} | {x['ok_hs2']} / {x['ok_v51']} | {x['n']} | {rat} | {pw} | "
                 f"{'WORSE' if nh_sig[i] else '-'} | {x['cov_hs2']:.3f} / {x['cov_v51']:.3f} |")
    # ------------------------------------------------------------------ verdict
    fails = [n for n, ok in (("V0", v0), ("V1", v1), ("P2a", p2a), ("P2b", p2b), ("P2c", p2c), ("no-harm (a)", nha)) if not ok]
    if not (v0 and v1):
        verdict = "INVALID"
    elif not fails:
        verdict = "RETAINED (component B, exploratory)"
    else:
        verdict = "REJECTED"
    J["criteria"] = {
        "P2a": {"pass": p2a, "cells_ge_59": sum(p2a_cells), "of": 12},
        "P2b": {"pass": p2b, "cells_itt_ge_090": p2b_n, "min_itt": min(itts), "of": 12},
        "P2c": {"pass": p2c, "cells_pass_holm": sum(pc_pass), "cells_pass_unadjusted": sum(pc_unadj), "of": 6,
                "detail": {f"{T}|{k}": strip(pc[i]) | {"holm_reject": rej[i]} for i, (T, k) in enumerate(P2C)}},
        "no_harm_a": {"pass": nha, "complete": nh_complete, "ratio_ok": sum(nh_ratio), "holm_sig_worse": sum(nh_sig), "coverage_ok": sum(nh_cov),
                      "of": 21, "detail": {f"{T}|{k}|{r}": strip(nh[i]) for i, (T, k, r) in enumerate(G)}},
        "failed": fails, "verdict": verdict}
    J["cells"] = {f"{T}|{k}|{m}": S[(T, k, m)] for (T, k, m) in S}
    L += ["", "## Verdict (component B alone)", "",
          f"- V0: {'PASS' if v0 else 'FAIL'}; V1: {'PASS' if v1 else 'FAIL'}",
          f"- P2a completion >= 59/60: {sum(p2a_cells)}/12 cells -> {'PASS' if p2a else 'FAIL'}",
          f"- P2b ITT >= 0.90 in >= 10/12 (got {p2b_n}/12), min >= 0.85 (got {min(itts):.3f}) -> {'PASS' if p2b else 'FAIL'}",
          f"- P2c rescued runs vs plugin_hs_cal, ratio < 1.10 by Holm(6) with >= 8 clusters: {sum(pc_pass)}/6 (need >= 4; "
          f"unadjusted upper 95% < 1.10: {sum(pc_unadj)}/6) -> {'PASS' if p2c else 'FAIL'}",
          f"- No-harm (a) on G: ratio <= 1.03 in {sum(nh_ratio)}/21, Holm(21) worse with >= 8 clusters {sum(nh_sig)}/21, "
          f"coverage kept >= 0.90 where v5_1 >= 0.90 in {sum(nh_cov)}/21, all 21 cells with 60 rows: {nh_complete} -> {'PASS' if nha else 'FAIL'}",
          "", f"**Verdict: {verdict}**" + (f" (failed: {', '.join(fails)})" if fails else "")]
    (OUT / "ruling.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (OUT / "ruling.json").write_text(json.dumps(J, indent=1, default=float), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
