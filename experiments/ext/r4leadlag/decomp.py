"""POST HOC descriptive decomposition (docs/ext/r4leadlag.md section 7; not part of the pre-registered rule).

Splits dIS(variant - v5_1) of the evaluation into a gate part and a width-factor part:
  gate part   = variant with v5_1's frozen factors (runs ext_r4leadlag_decomp_{latent,clean}) - v5_1
  factor part = variant with its own factors (ext_r4leadlag_eval_*) - variant with v5_1's factors
Same paired cluster bootstrap as analyze.py (B = 20000, seed 20261104); Holm reported over the cells shown,
for information only.

Run: python experiments/ext/r4leadlag/decomp.py -> results/ext_r4leadlag_rule/decomp.{md,json}
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze as AZ  # noqa: E402

CELLS = AZ.PRIMARY + [("clean", 150, 0.2), ("clean", 150, 0.5)]


def main():
    ev = AZ.by_method(AZ.load("ext_r4leadlag_eval_latent") + AZ.load("ext_r4leadlag_eval_clean"))
    dc = AZ.by_method(AZ.load("ext_r4leadlag_decomp_latent") + AZ.load("ext_r4leadlag_decomp_clean"))
    out, L = {}, ["# r4leadlag: post hoc decomposition (descriptive; generated by experiments/ext/r4leadlag/decomp.py)", "",
                  "| variant | scenario | T | stated | cov v5_1 | cov gate-only | IS v5_1 | IS gate-only | IS own factor | "
                  "gate part [95% CI] | p | factor part [95% CI] | p |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for tag, m in AZ.VARIANTS.items():
        g_rows = {}
        for sc, T, r in CELLS:
            keys = AZ.cell_keys(ev, sc, T, "missing", r)
            Dg = {AZ.REF: ev[AZ.REF], m: dc[m]}
            gate = AZ.paired(Dg, m, keys)
            Df = {AZ.REF: dc[m], m: ev[m]}
            fac = AZ.paired(Df, m, keys)
            cov_g, fail_g = AZ.coverage_itt(Dg, m, keys)
            cov_r, _ = AZ.coverage_itt(Dg, AZ.REF, keys)
            g_rows[f"{sc}|{T}|{r}"] = {"gate": gate, "factor": fac, "cov_gate_only": cov_g, "fail_gate_only": fail_g,
                                       "cov_ref": cov_r}
            L.append(f"| {tag} | {sc} | {T} | missing-{r} | {cov_r:.3f} | {cov_g:.3f} | {gate['IS_ref']:.3f} | {gate['IS_m']:.3f} | "
                     f"{fac['IS_m']:.3f} | {gate['est']:+.3f} [{gate['lo']:+.3f}, {gate['hi']:+.3f}] | {gate['p_two']:.4f} | "
                     f"{fac['est']:+.3f} [{fac['lo']:+.3f}, {fac['hi']:+.3f}] | {fac['p_two']:.4f} |")
        hp = AZ.holm([v["gate"]["p_two"] for v in g_rows.values()])
        better = sum(h and v["gate"]["est"] < 0 for h, v in zip(hp, g_rows.values()))
        worse = sum(h and v["gate"]["est"] > 0 for h, v in zip(hp, g_rows.values()))
        out[tag] = {"cells": g_rows, "gate_holm_better": better, "gate_holm_worse": worse, "n_cells": len(g_rows)}
        L.append(f"| {tag} | gate part, Holm 0.05 over {len(g_rows)}: better {better}, worse {worse} | | | | | | | | | | | |")
    AZ.OUT.mkdir(parents=True, exist_ok=True)
    (AZ.OUT / "decomp.md").write_text("\n".join(L) + "\n")
    (AZ.OUT / "decomp.json").write_text(json.dumps(out, indent=1))
    print("\n".join(L))


if __name__ == "__main__":
    main()
