"""Conformal factors of r4mondrian from the D-07H development calibration run (docs/ext/r4mondrian.md).

1. V2 (implementation check): the runner's grid rule (run_experiment.calibrate: C_GRID 1.0..10, target
   min(0.95, max coverage - 0.005)) applied to the logged |C_true - mid| and pre-scaled half-widths
   (0.5 h) of replicate 0 must reproduce every tolerant_v5_1|T|kind factor of
   experiments/ext/v51/frozen_v4_v51.json.
2. q tables: replicate 0 (primary, the same cases as v5_1's factors) -> experiments/ext/r4mondrian/q_table.json;
   replicates 0-2 (sensitivity) -> experiments/ext/r4mondrian/q_table_rep3.json.
3. Design facts on D-07H only: class sizes, M0 factor vs frozen effective factor.

Run: python experiments/ext/r4mondrian/calibrate.py  -> results/ext_r4mondrian_cal/{calibration.md, calibration.json}
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments"))
from paper4 import ext_r4mondrian as X  # noqa: E402
from run_experiment import C_GRID  # noqa: E402

KINDS = ["none", "extra", "missing", "reversed"]
OUT = ROOT / "results" / "ext_r4mondrian_cal"
HERE = Path(__file__).resolve().parent


def grid_factor(dist, half):
    cov = np.array([(dist <= c * half).mean() for c in C_GRID])
    target = min(0.95, cov.max() - 0.005)
    return float(C_GRID[np.argmax(cov >= target)])


def main():
    P = dict(np.load(OUT / "pairs.npz"))
    frozen = json.loads((ROOT / "experiments/ext/v51/frozen_v4_v51.json").read_text())
    s_all = X.scores(P["C_t"], P["mid"], P["h"])
    res = {"V2": [], "classes": [], "lost_or_zero_h": int((P["h"] <= 0).sum())}
    L = ["# r4mondrian: calibration on D-07H development (generated by experiments/ext/r4mondrian/calibrate.py)", "",
         f"Pairs: {len(s_all)} non-null pairs over 3 replicates; pairs with h = 0: {res['lost_or_zero_h']}; "
         f"infinite scores: {int(np.isinf(s_all).sum())}.", "",
         "## V2: runner grid rule on logged replicate-0 scores vs frozen tolerant_v5_1 factors", "",
         "| T | kind | N | grid factor (re-derived) | frozen | equal |", "|---|---|---|---|---|---|"]
    tables = {}
    for tag, reps in (("rep1", [0]), ("rep3", [0, 1, 2])):
        by = {}
        for T in (40, 80, 150):
            for kc, kind in enumerate(KINDS):
                m = (P["T"] == T) & (P["stated"] == kc) & np.isin(P["rep"], reps)
                by[(T, kind)] = (s_all[m], P["R"][m].astype(bool))
                if tag == "rep1":
                    dist = np.abs(P["C_t"][m] - P["mid"][m])
                    g = grid_factor(dist, 0.5 * P["h"][m])
                    fz = frozen[f"tolerant_v5_1|{T}|{kind}"]
                    ok = abs(g - fz) < 1e-9
                    res["V2"].append({"T": T, "kind": kind, "N": int(m.sum()), "grid": g, "frozen": fz, "equal": ok})
                    L.append(f"| {T} | {kind} | {int(m.sum())} | {g} | {fz} | {'yes' if ok else 'NO'} |")
        tables[tag] = X.build_q_table(by)
    res["V2_pass"] = all(r["equal"] for r in res["V2"])
    L += ["", f"**V2: {'PASS' if res['V2_pass'] else 'FAIL'}** ({sum(r['equal'] for r in res['V2'])}/12).", ""]
    for tag in ("rep1", "rep3"):
        t = tables[tag]
        L += [f"## q table ({tag}; effective factors, interval = mid ± q·h)", "",
              "| T | kind | N all | q M0 | 0.5 × frozen | q M0 − 0.5 × frozen | N R | q R | N S | q S | merged |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for T in (40, 80, 150):
            for kind in KINDS:
                a, r, s = t[f"{T}|{kind}|all"], t[f"{T}|{kind}|R"], t[f"{T}|{kind}|S"]
                fe = 0.5 * frozen[f"tolerant_v5_1|{T}|{kind}"]
                L.append(f"| {T} | {kind} | {a['N']} | {a['q']:.4f} | {fe:.2f} | {a['q'] - fe:+.4f} | {r['N']} | {r['q']:.4f} | "
                         f"{s['N']} | {s['q']:.4f} | {'yes' if r['merged'] else 'no'} |")
                if tag == "rep1":
                    res["classes"].append({"T": T, "kind": kind, "N": a["N"], "q_M0": a["q"], "frozen_eff": fe,
                                           "N_R": r["N"], "q_R": r["q"], "N_S": s["N"], "q_S": s["q"], "merged": r["merged"]})
        L.append("")
        meta = {"_note": f"r4mondrian conformal factors ({tag}): key T|stated kind|class (all = M0; R, S = M2 classes, "
                         "merged into the pooled q when a class has N < 50). Effective factor on the UNSCALED percentile "
                         "half-width h of tolerant_v5_1: interval = mid +/- q*h. Source: results/ext_r4mondrian_cal/pairs.npz "
                         f"(D-07H development, calibration-phase seeds, replicates {reps if tag == 'rep3' else [0]}).",
                **t}
        name = "q_table.json" if tag == "rep1" else "q_table_rep3.json"
        (HERE / name).write_text(json.dumps(meta, indent=1), encoding="utf-8")
    (OUT / "calibration.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (OUT / "calibration.json").write_text(json.dumps({**res, "tables": tables}, indent=1), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
