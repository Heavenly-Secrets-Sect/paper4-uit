"""R2-2(a): pair tolerant_v5 (ext_narrow_eval) with pselect_cal / fullvar_cal / bvar_cal / ida_cal
(ext_redteam_calbase) and targeted_lp_cal / targeted_lp (ext_tlp_eval) through identical tolerant_v4
rows. No estimation. Rule in docs/ext/v51.md, part (a).

Run: python experiments/ext/v51/pair_v5.py   -> results/ext_v51_pairs/{pairing.json, pairs.md, pairs.json}
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import CELLS, DAMAGED, RES, TS, cell_stats, check_identical, fmt_p, holm, index, load, paired  # noqa: E402

OUT = RES / "ext_v51_pairs"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    nar = load("ext_narrow_eval")
    red = load("ext_redteam_calbase")
    tlp = load("ext_tlp_eval")
    a2b = load("a2b_pselect")
    checks = {
        "v4 narrow vs redteam": check_identical(nar, red, "tolerant_v4"),
        "v4 narrow vs tlp": check_identical(nar, tlp, "tolerant_v4"),
        "v4 redteam vs tlp": check_identical(red, tlp, "tolerant_v4"),
        "v4 narrow vs a2b_pselect": check_identical(nar, a2b, "tolerant_v4"),
        "plugin redteam vs tlp": check_identical(red, tlp, "plugin"),
        "plugin redteam vs a2b_pselect": check_identical(red, a2b, "plugin"),
        "pselect_union tlp vs a2b_pselect": check_identical(tlp, a2b, "pselect_union"),
    }
    (OUT / "pairing.json").write_text(json.dumps(checks, indent=1))
    paired_ok = {"redteam": checks["v4 narrow vs redteam"]["ok"], "tlp": checks["v4 narrow vs tlp"]["ok"]}
    rows = ([r for r in nar if r["method"] in ("tolerant_v4", "tolerant_v5")]
            + [r for r in red if r["method"] in ("pselect_cal", "fullvar_cal", "bvar_cal", "ida_cal")]
            + [r for r in tlp if r["method"] in ("targeted_lp", "targeted_lp_cal", "pselect_union")])
    idx = index(rows)
    methods = ["tolerant_v4", "tolerant_v5", "pselect_cal", "fullvar_cal", "bvar_cal", "ida_cal", "pselect_union",
               "targeted_lp", "targeted_lp_cal"]
    refs = ["pselect_cal", "fullvar_cal", "targeted_lp_cal", "bvar_cal", "ida_cal", "targeted_lp", "tolerant_v4"]
    S, P = {}, {}
    for T in TS:
        for kind, rate in CELLS:
            for m in methods:
                S[(m, T, kind, rate)] = cell_stats(rows, m, T, kind, rate)
            for ref in refs:
                P[(ref, T, kind, rate)] = paired(idx, "tolerant_v5", ref, T, kind, rate)
    out = ["# ext_v51_pairs: tolerant_v5 paired with calibrated baselines (generated by experiments/ext/v51/pair_v5.py)", "",
           "## Pairing check", ""]
    for k, v in checks.items():
        out.append(f"- {k}: {v['identical']}/{v['common']} identical ({v['n_a']} vs {v['n_b']} rows) -> **{v['ok']}**")
    out += ["", "## Cells: coverage / IS / width", "", "| T | cell | " + " | ".join(methods) + " |",
            "|---|---|" + "---|" * len(methods)]
    for T in TS:
        for kind, rate in CELLS:
            cs = []
            for m in methods:
                s = S[(m, T, kind, rate)]
                cs.append("–" if s is None else f"{s['cov']:.3f} / {s['IS']:.2f} / {s['width']:.2f}"
                          + ("" if s["n"] == s["of"] else f" [{s['n']}/{s['of']}]"))
            out.append(f"| {T} | {kind}-{rate} | " + " | ".join(cs) + " |")
    out += ["", "## Paired IS difference v5 − reference, 95% CI clustered by topology (one-sided p: v5 better / v5 worse)", "",
            "| T | cell | " + " | ".join(f"v5 − {r}" for r in refs) + " |", "|---|---|" + "---|" * len(refs)]
    for T in TS:
        for kind, rate in CELLS:
            cs = []
            for ref in refs:
                p = P[(ref, T, kind, rate)]
                cs.append("–" if p is None else f"{fmt_p(p)} (p<{p['p_less']:.4f} / p>{p['p_greater']:.4f})")
            out.append(f"| {T} | {kind}-{rate} | " + " | ".join(cs) + " |")
    # rule of part (a)
    out += ["", "## Rule of part (a) (docs/ext/v51.md): counts over the 18 damaged cells", ""]
    summary = {}
    for X in ("pselect_cal", "fullvar_cal", "targeted_lp_cal", "bvar_cal", "ida_cal", "targeted_lp"):
        win, lose, pw, pl, detail = [], [], [], [], []
        for T in TS:
            for kind, rate in DAMAGED:
                s5, sx, p = S[("tolerant_v5", T, kind, rate)], S[(X, T, kind, rate)], P[(X, T, kind, rate)]
                w = s5["cov"] >= 0.90 and p["hi"] < 0
                l_ = sx["cov"] >= 0.90 and p["lo"] > 0
                win.append(w); lose.append(l_)
                pw.append(p["p_less"] if s5["cov"] >= 0.90 else 1.0)
                pl.append(p["p_greater"] if sx["cov"] >= 0.90 else 1.0)
                detail.append((T, kind, rate, w, l_))
        hw, hl = holm(pw), holm(pl)
        cells_w = [f"{T} {k}-{r}" for (T, k, r, w, _), h in zip(detail, hw) if w]
        cells_l = [f"{T} {k}-{r}" for (T, k, r, _, l_), h in zip(detail, hl) if l_]
        summary[X] = {"v5_wins": sum(win), "v5_wins_holm": sum(hw), "X_wins": sum(lose), "X_wins_holm": sum(hl),
                      "v5_win_cells": cells_w, "X_win_cells": cells_l,
                      "v5_win_cells_holm": [f"{T} {k}-{r}" for (T, k, r, _, _), h in zip(detail, hw) if h],
                      "X_win_cells_holm": [f"{T} {k}-{r}" for (T, k, r, _, _), h in zip(detail, hl) if h]}
        tag = "" if X != "targeted_lp" and X != "targeted_lp_cal" else ""
        out.append(f"- v5 vs `{X}` (paired={paired_ok['tlp' if 'lp' in X else 'redteam']}): v5 wins {sum(win)}/18 "
                   f"(Holm {sum(hw)}/18); `{X}` wins {sum(lose)}/18 (Holm {sum(hl)}/18)")
        out.append(f"  - v5 win cells: {', '.join(cells_w) or 'none'}")
        out.append(f"  - `{X}` win cells: {', '.join(cells_l) or 'none'}")
        out.append(f"  - v5 win cells after Holm: {', '.join(summary[X]['v5_win_cells_holm']) or 'none'}")
    (OUT / "pairs.md").write_text("\n".join(out) + "\n")
    js = {"pairing": checks, "summary": summary,
          "cells": {f"{m}|{T}|{k}|{r}": s for (m, T, k, r), s in S.items()},
          "paired": {f"v5-{ref}|{T}|{k}|{r}": p for (ref, T, k, r), p in P.items()}}
    (OUT / "pairs.json").write_text(json.dumps(js, indent=1))
    print("\n".join(out))


if __name__ == "__main__":
    main()
