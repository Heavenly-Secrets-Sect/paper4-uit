"""R2-2(c): apply the pre-registered a1 rule (docs/ext/v51.md, part (c)) to results/ext_v51_a1 (T 80/150)
and results/ext_v51_a1t40 (T 40) together.

Run: python experiments/ext/v51/rule_a1.py  -> results/ext_v51_a1/{ruling.md, ruling.json}
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import RES, cell_stats, fmt_p, holm, index, load, paired  # noqa: E402

RUN = "ext_v51_a1"
SCEN = ["latent1", "latent3", "noise0.1"]
TS = [40, 80, 150]
RUNS = ["ext_v51_a1", "ext_v51_a1t40"]
CELLS = [("none", 0.0), ("missing", 0.2), ("reversed", 0.2)]
METHODS = ["tolerant_v4", "tolerant_v5", "tolerant_v5_1"]


def cov_p_below(rows, m, sc, T, kind, rate, thr=0.90, B=10_000):
    """One-sided bootstrap p (clustered by topology) for pooled coverage < thr."""
    g = [r for r in rows if r["method"] == m and r.get("scenario") == sc and r["T"] == T and r["kind"] == kind
         and r["rate"] == rate and r["status"] == "ok"]
    by = {}
    for r in g:
        a = by.setdefault(r["topology"], [0, 0])
        a[0] += r["n_covered_nonnull"]; a[1] += r["n_nonnull"]
    c = np.array(list(by.values()), dtype=float)
    rng = np.random.default_rng(2)
    pick = rng.integers(0, len(c), size=(B, len(c)))
    cov = c[pick, 0].sum(1) / c[pick, 1].sum(1)
    return (1 + int((cov >= thr).sum())) / (B + 1)


def main():
    rows = [r for run in RUNS for r in load(run)]
    idx = index(rows)
    S, P = {}, {}
    out = [f"# {RUN}: a1 scenarios (generated by experiments/ext/v51/rule_a1.py)", ""]
    ev = RES / "ext_v51_eval" / "calibration.json"
    for run in RUNS:
        cal = json.loads((RES / run / "calibration.json").read_text())
        if ev.exists():
            evc = json.loads(ev.read_text())
            for m in ("tolerant_v5_1", "tolerant_v5"):
                keys = [k for k in cal if k.startswith(m + "|")]
                same = [k for k in keys if evc.get(k) == cal[k]]
                out.append(f"{run}: width factors of {m} identical to ext_v51_eval: {len(same)}/{len(keys)} keys "
                           f"(ext_v51_eval has {'no ' if not any(k.startswith(m + '|') for k in evc) else ''}{m} keys)")
        out.append(f"{run}: factors " + ", ".join(f"{k}={v}" for k, v in sorted(cal.items()) if not k.startswith("mod|")))
    out += ["", "| scenario | T | cell | " + " | ".join(METHODS) + " | v5_1 − v4 | v5 − v4 | v5_1 targeted share |",
            "|---|---|---|" + "---|" * (len(METHODS) + 3)]
    for sc in SCEN:
        for T in TS:
            for kind, rate in CELLS:
                cs = []
                for m in METHODS:
                    s = cell_stats(rows, m, T, kind, rate, scenario=sc)
                    S[(m, sc, T, kind, rate)] = s
                    cs.append("–" if s is None else f"{s['cov']:.3f} / {s['IS']:.3f} / {s['width']:.2f}"
                              + ("" if s["n"] == s["of"] else f" [{s['n']}/{s['of']}]"))
                for m in ("tolerant_v5_1", "tolerant_v5"):
                    P[(m, sc, T, kind, rate)] = paired(idx, m, "tolerant_v4", T, kind, rate, scenario=sc)
                    cs.append(fmt_p(P[(m, sc, T, kind, rate)]))
                s51 = S[('tolerant_v5_1', sc, T, kind, rate)]
                cs.append("–" if s51 is None or s51['info_v51_targeted'] is None else f"{s51['info_v51_targeted']:.2f}")
                out.append(f"| {sc} | {T} | {kind}-{rate} | " + " | ".join(cs) + " |")
    out += ["", "## Rule (part (c))", ""]
    res = {}
    for m in METHODS:
        for sc in SCEN:
            passed, pbel, lines = [], [], []
            for T in TS:
                for kind, rate in CELLS:
                    s = S[(m, sc, T, kind, rate)]
                    if s is None:   # tolerant_v5 only in the T = 40 run (docs/ext/v51.md)
                        continue
                    passed.append(s["cov"] >= 0.90)
                    pbel.append(cov_p_below(rows, m, sc, T, kind, rate))
                    if s["cov"] < 0.90:
                        lines.append(f"T={T} {kind}-{rate}: {s['cov']:.3f}")
            below = holm(pbel)
            res[f"{m}|{sc}"] = {"pass": sum(passed), "of": len(passed), "sig_below_holm": sum(below), "fails": lines}
            tag = " **(RULE)**" if (m == "tolerant_v5_1" and sc == "latent1") else ""
            out.append(f"- {m} {sc}{tag}: cov >= 0.90 in {sum(passed)}/{len(passed)} cells; significantly below 0.90 after Holm: "
                       f"{sum(below)}/{len(passed)}; failing cells: {', '.join(lines) or 'none'}")
    v = res["tolerant_v5_1|latent1"]["pass"] == res["tolerant_v5_1|latent1"]["of"] == 9
    res["verdict_latent1_v5_1"] = v
    out += ["", f"-> latent1 rule for tolerant_v5_1: **{'PASS' if v else 'FAIL'}** (v5 reported: "
                f"{res['tolerant_v5|latent1']['pass']}/{res['tolerant_v5|latent1']['of']}, T = 40 only)"]
    # descriptive: IS ratio vs v4
    worse = []
    for m in ("tolerant_v5_1", "tolerant_v5"):
        have = [(sc, T, k, r) for sc in SCEN for T in TS for k, r in CELLS if P[(m, sc, T, k, r)] is not None]
        pg = [P[(m,) + c]["p_greater"] for c in have]
        h = holm(pg)
        n_ratio = sum(1 for (sc, T, k, r) in have
                      if S[(m, sc, T, k, r)]["IS"] > 1.05 * S[("tolerant_v4", sc, T, k, r)]["IS"])
        res[f"{m}_worse_than_v4"] = {"ratio_gt_1.05": n_ratio, "sig_worse_holm": sum(h)}
        out.append(f"- Reported: {m} IS > 1.05 x v4 in {n_ratio}/{len(pg)} cells; significantly worse than v4 after Holm: {sum(h)}/{len(pg)}")
    (RES / RUN).mkdir(parents=True, exist_ok=True)
    (RES / RUN / "ruling.md").write_text("\n".join(out) + "\n")
    (RES / RUN / "ruling.json").write_text(json.dumps({"rule": res, "cells": {"|".join(map(str, k)): s for k, s in S.items()},
                                                        "paired": {"|".join(map(str, k)): p for k, p in P.items()}}, indent=1))
    print("\n".join(out))


if __name__ == "__main__":
    main()
