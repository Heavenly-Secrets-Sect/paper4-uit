"""R2-2(b): apply the pre-registered rule of tolerant_v5_1 (docs/ext/v51.md) to results/ext_v51_eval
mechanically, with Holm counts, and pair v5_1 with pselect_cal / fullvar_cal (ext_redteam_calbase),
targeted_lp_cal (ext_tlp_eval) and round-1 tolerant_v5 / v5_cal2 (ext_narrow_eval / ablation) through
identical tolerant_v4 rows.

Run: python experiments/ext/v51/rule_eval.py  -> results/ext_v51_eval/{ruling.md, ruling.json}
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import CELLS, DAMAGED, RES, TS, cell_stats, check_identical, fmt_p, holm, index, load, paired  # noqa: E402

RUN = "ext_v51_eval"
M51 = "tolerant_v5_1"


def main():
    ev = load(RUN)
    red, tlp, nar, abl = load("ext_redteam_calbase"), load("ext_tlp_eval"), load("ext_narrow_eval"), load("ext_narrow_ablation")
    checks = {"v4 ext_v51_eval vs ext_redteam_calbase": check_identical(ev, red, "tolerant_v4"),
              "v4 ext_v51_eval vs ext_tlp_eval": check_identical(ev, tlp, "tolerant_v4"),
              "v4 ext_v51_eval vs ext_narrow_eval": check_identical(ev, nar, "tolerant_v4"),
              "v4 ext_v51_eval vs ext_narrow_ablation": check_identical(ev, abl, "tolerant_v4")}
    ok_red = checks["v4 ext_v51_eval vs ext_redteam_calbase"]["ok"]
    ok_tlp = checks["v4 ext_v51_eval vs ext_tlp_eval"]["ok"]
    ok_nar = checks["v4 ext_v51_eval vs ext_narrow_eval"]["ok"]
    ok_abl = checks["v4 ext_v51_eval vs ext_narrow_ablation"]["ok"]
    rows = ([r for r in ev if r["method"] in ("tolerant_v4", M51)]
            + ([r for r in red if r["method"] in ("pselect_cal", "fullvar_cal")] if ok_red else [])
            + ([r for r in tlp if r["method"] in ("targeted_lp_cal", "pselect_union")] if ok_tlp else [])
            + ([r for r in nar if r["method"] == "tolerant_v5"] if ok_nar else [])
            + ([r for r in abl if r["method"] == "tolerant_v5_cal2"] if ok_abl else []))
    idx = index(rows)
    methods = ["tolerant_v4", M51, "tolerant_v5", "tolerant_v5_cal2", "pselect_cal", "fullvar_cal", "targeted_lp_cal"]
    refs = ["tolerant_v4", "pselect_cal", "fullvar_cal", "targeted_lp_cal", "tolerant_v5", "tolerant_v5_cal2"]
    S, P = {}, {}
    for T in TS:
        for kind, rate in CELLS:
            for m in methods:
                S[(m, T, kind, rate)] = cell_stats(rows, m, T, kind, rate)
            for ref in refs:
                P[(ref, T, kind, rate)] = paired(idx, M51, ref, T, kind, rate)
    out = [f"# {RUN}: ruling of tolerant_v5_1 (generated by experiments/ext/v51/rule_eval.py)", "", "## Pairing checks", ""]
    for k, v in checks.items():
        out.append(f"- {k}: {v['identical']}/{v['common']} identical ({v['n_a']} vs {v['n_b']} rows) -> **{v['ok']}**")
    cal = json.loads((RES / RUN / "calibration.json").read_text())
    out += ["", "## Width factors of tolerant_v5_1 (effective = runner factor x 0.5)", "",
            "| T | none | extra | missing | reversed |", "|---|---|---|---|---|"]
    for T in TS:
        out.append(f"| {T} | " + " | ".join(f"{cal.get(f'{M51}|{T}|{k}', float('nan')) * 0.5:.2f}"
                                          for k in ("none", "extra", "missing", "reversed")) + " |")
    out += ["", "## Cells: coverage / IS / width; for v5_1 also share of runs in the targeted branch and mean r", "",
            "| T | cell | " + " | ".join(methods) + " | v5_1 targeted share, r |", "|---|---|" + "---|" * (len(methods) + 1)]
    for T in TS:
        for kind, rate in CELLS:
            cs = []
            for m in methods:
                s = S[(m, T, kind, rate)]
                cs.append("–" if s is None else f"{s['cov']:.3f} / {s['IS']:.3f} / {s['width']:.2f}"
                          + ("" if s["n"] == s["of"] else f" [{s['n']}/{s['of']}]"))
            s = S[(M51, T, kind, rate)]
            cs.append(f"{s['info_v51_targeted']:.2f}, {s['info_v51_ratio']:.2f}")
            out.append(f"| {T} | {kind}-{rate} | " + " | ".join(cs) + " |")
    out += ["", "## Paired IS difference v5_1 − reference, 95% CI clustered by topology (one-sided p: better / worse)", "",
            "| T | cell | " + " | ".join(f"v5_1 − {r}" for r in refs) + " |", "|---|---|" + "---|" * len(refs)]
    for T in TS:
        for kind, rate in CELLS:
            cs = []
            for ref in refs:
                p = P[(ref, T, kind, rate)]
                cs.append("–" if p is None else f"{fmt_p(p)} ({p['p_less']:.4f} / {p['p_greater']:.4f})")
            out.append(f"| {T} | {kind}-{rate} | " + " | ".join(cs) + " |")

    # ---------------- pre-registered rule ----------------
    out += ["", "## Pre-registered rule (docs/ext/v51.md, part (b))", ""]
    res = {}
    # C1
    c1, c1p = [], []
    for rate in (0.2, 0.5):
        s, p = S[(M51, 40, "missing", rate)], P[("tolerant_v4", 40, "missing", rate)]
        ok = s is not None and p is not None and s["cov"] >= 0.90 and p["hi"] < 0
        c1.append(ok); c1p.append(p["p_less"] if s["cov"] >= 0.90 else 1.0)
        out.append(f"- C1 T=40 missing-{rate}: cov {s['cov']:.3f}, v5_1 − v4 {fmt_p(p)} (p {p['p_less']:.4f}) -> {'PASS' if ok else 'FAIL'}")
    c1h = holm(c1p)
    # C2
    c2, c2harm = [], []
    for T in (80, 150):
        for kind, rate in DAMAGED:
            s, v, p = S[(M51, T, kind, rate)], S[("tolerant_v4", T, kind, rate)], P[("tolerant_v4", T, kind, rate)]
            ok = s["cov"] >= 0.90 and s["IS"] <= 1.05 * v["IS"]
            c2.append(ok); c2harm.append(p["p_greater"])
            out.append(f"- C2 T={T} {kind}-{rate}: cov {s['cov']:.3f}, IS {s['IS']:.3f} vs v4 {v['IS']:.3f} (ratio {s['IS'] / v['IS']:.3f}); "
                       f"v5_1 − v4 {fmt_p(p)} -> {'PASS' if ok else 'FAIL'}")
    c2h = holm(c2harm)
    # C3
    c3, c3harm = [], []
    for T, kind, rate in [(40, "none", 0.0), (80, "none", 0.0), (150, "none", 0.0)] + [(40, k, r) for k in ("extra", "reversed") for r in (0.2, 0.5)]:
        s, v, p = S[(M51, T, kind, rate)], S[("tolerant_v4", T, kind, rate)], P[("tolerant_v4", T, kind, rate)]
        ok = s["IS"] <= 1.05 * v["IS"]
        c3.append(ok); c3harm.append(p["p_greater"])
        out.append(f"- C3 T={T} {kind}-{rate}: IS {s['IS']:.3f} vs v4 {v['IS']:.3f} (ratio {s['IS'] / v['IS']:.3f}); v5_1 − v4 {fmt_p(p)} -> {'PASS' if ok else 'FAIL'}")
    c3h = holm(c3harm)
    # C4 (T40 conditions vs calibrated baselines)
    c4a, c4ap, c4b = [], [], []
    for rate in (0.2, 0.5):
        s = S[(M51, 40, "missing", rate)]
        pa, pb = P[("pselect_cal", 40, "missing", rate)], P[("targeted_lp_cal", 40, "missing", rate)]
        oka = ok_red and pa is not None and s["cov"] >= 0.90 and pa["hi"] < 0
        okb = ok_tlp and pb is not None and pb["lo"] <= 0
        c4a.append(oka); c4ap.append(pa["p_less"] if (pa and s["cov"] >= 0.90) else 1.0); c4b.append(okb)
        out.append(f"- C4a T=40 missing-{rate}: v5_1 − pselect_cal {fmt_p(pa)} (paired={ok_red}) -> {'PASS' if oka else 'FAIL'}")
        out.append(f"- C4b T=40 missing-{rate}: v5_1 − targeted_lp_cal {fmt_p(pb)} (paired={ok_tlp}); lower bound <= 0 -> {'PASS' if okb else 'FAIL'}")
    c4ah = holm(c4ap)
    verdict = all(c1) and all(c2) and all(c3) and all(c4a) and all(c4b)
    verdict_holm = all(c1h) and all(c2) and all(c3) and all(c4ah) and all(c4b)
    out += ["",
            f"C1 {sum(c1)}/2 (Holm {sum(c1h)}/2); C2 {sum(c2)}/12 (cells where v5_1 is significantly WORSE than v4 after Holm: {sum(c2h)}/12); "
            f"C3 {sum(c3)}/7 (significantly worse after Holm: {sum(c3h)}/7); C4a {sum(c4a)}/2 (Holm {sum(c4ah)}/2); C4b {sum(c4b)}/2",
            f"-> **tolerant_v5_1 {'RETAINED' if verdict else 'REJECTED'}** (verdict with the CI-based conditions replaced by their Holm version: "
            f"{'RETAINED' if verdict_holm else 'REJECTED'})", ""]
    res.update({"C1": c1, "C1_holm": c1h, "C2": c2, "C2_worse_holm": c2h, "C3": c3, "C3_worse_holm": c3h, "C4a": c4a, "C4a_holm": c4ah,
                "C4b": c4b, "verdict": verdict, "verdict_holm": verdict_holm})
    # descriptive counts vs calibrated baselines over 18 damaged cells
    for X in ("pselect_cal", "fullvar_cal", "targeted_lp_cal", "tolerant_v4"):
        win, pw = [], []
        for T in TS:
            for kind, rate in DAMAGED:
                s, p = S[(M51, T, kind, rate)], P[(X, T, kind, rate)]
                if p is None:
                    win.append(False); pw.append(1.0); continue
                win.append(s["cov"] >= 0.90 and p["hi"] < 0); pw.append(p["p_less"] if s["cov"] >= 0.90 else 1.0)
        hw = holm(pw)
        res[f"wins_vs_{X}"] = [sum(win), sum(hw)]
        out.append(f"- Reported: v5_1 cov >= 0.90 and CI upper (v5_1 − {X}) < 0 in {sum(win)}/18 damaged cells (Holm {sum(hw)}/18)")
    (RES / RUN / "ruling.md").write_text("\n".join(out) + "\n")
    (RES / RUN / "ruling.json").write_text(json.dumps({"pairing": checks, "rule": res,
                                                        "cells": {f"{m}|{T}|{k}|{r}": s for (m, T, k, r), s in S.items()},
                                                        "paired": {f"v5_1-{ref}|{T}|{k}|{r}": p for (ref, T, k, r), p in P.items()}},
                                                       indent=1))
    print("\n".join(out))


if __name__ == "__main__":
    main()
